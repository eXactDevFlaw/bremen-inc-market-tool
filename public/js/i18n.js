export function getLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "de") return stored;
  } catch {
    // localStorage kann in seltenen Faellen (privater Modus etc.) fehlschlagen - dann Default.
  }
  return DEFAULT_LANG;
}

export function setLang(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Speichern fehlgeschlagen - Sprache gilt dann nur fuer die aktuelle Seitenladung.
  }
}

function interpolate(str, params) {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, key) => (key in params ? String(params[key]) : `{${key}}`));
}

/** Uebersetzt `key` in der aktuellen Sprache; faellt auf Englisch, dann auf den Key selbst zurueck. */
export function t(key, params) {
  const lang = getLang();
  const raw = dict[lang]?.[key] ?? dict.en[key] ?? key;
  return interpolate(raw, params);
}

/** Wendet alle [data-i18n] / [data-i18n-html] / [data-i18n-placeholder]-Attribute im gegebenen Root auf die aktuelle Sprache an. */
export function applyStaticTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  document.documentElement.lang = getLang();
}
